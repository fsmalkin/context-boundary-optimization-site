"""Command-line tools for the context_contract reference library."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Any, Mapping

from .contract import AXES, ContextContract, ObligationSpec
from .gate import Gate


AUTHORITY_RE = re.compile(
    r"\b(irreversible|external|externally-visible|send|email|delete|refund|charge|payment|cost|cancel|book|submit|update|modify|write)\b",
    re.IGNORECASE,
)
PROVENANCE_RE = re.compile(
    r"\b(source|cite|citation|evidence|current|latest|fresh|document|report|claim|reference)\b",
    re.IGNORECASE,
)
MEMORY_RE = re.compile(
    r"\b(multi-step|workflow|state|status|pending|sequence|session|prior|previous|handoff)\b",
    re.IGNORECASE,
)
PRIVACY_RE = re.compile(
    r"\b(user|customer|personal|private|pii|address|email|phone|account|third-party|sensitive)\b",
    re.IGNORECASE,
)
UNCERTAINTY_RE = re.compile(
    r"\b(ambiguous|conflict|unknown|optional|decide|confidence|ask|clarify|missing)\b",
    re.IGNORECASE,
)
REQUIRED_CONTEXT_RE = re.compile(
    r"\b(require|required|needs|depends|input|parameter|context|before)\b",
    re.IGNORECASE,
)


def main(argv: list[str] | None = None) -> int:
    """Run the CLI and return a process status code."""

    parser = argparse.ArgumentParser(prog="python -m context_contract")
    subparsers = parser.add_subparsers(dest="command", required=True)

    scaffold_parser = subparsers.add_parser("scaffold", help="emit service integration starter code")
    scaffold_parser.add_argument("contract_json", type=Path)
    scaffold_parser.add_argument("--out", type=Path, help="write the scaffold to this file")
    scaffold_parser.set_defaults(func=cmd_scaffold)

    advise_parser = subparsers.add_parser("advise", help="draft a heuristic contract skeleton")
    advise_parser.add_argument("service_json", type=Path)
    advise_parser.add_argument("--out", type=Path, help="write the advisory JSON to this file")
    advise_parser.set_defaults(func=cmd_advise)

    check_parser = subparsers.add_parser("check", help="run the deterministic gate for one action")
    check_parser.add_argument("contract_json", type=Path)
    check_parser.add_argument("action_json", type=Path)
    check_parser.add_argument("--state", type=Path, help="optional runtime state JSON")
    check_parser.set_defaults(func=cmd_check)

    args = parser.parse_args(argv)
    args.func(args)
    return 0


def cmd_scaffold(args: argparse.Namespace) -> None:
    contract = ContextContract.read_json(args.contract_json)
    text = render_scaffold(contract)
    write_or_print(text, args.out)


def cmd_advise(args: argparse.Namespace) -> None:
    service = read_json(args.service_json)
    output = advise_service(service)
    text = json.dumps(output, indent=2, sort_keys=True) + "\n"
    write_or_print(text, args.out)


def cmd_check(args: argparse.Namespace) -> None:
    contract = ContextContract.read_json(args.contract_json)
    action = read_json(args.action_json)
    state = read_json(args.state) if args.state else {}
    decision = Gate(contract).check(action, state=state)
    print(json.dumps(decision.to_dict(), indent=2, sort_keys=True))


def read_json(path: Path | None) -> Any:
    if path is None:
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def write_or_print(text: str, path: Path | None) -> None:
    if path is None:
        sys.stdout.write(text)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def render_scaffold(contract: ContextContract) -> str:
    """Return runnable starter Python for a service call site."""

    contract_literal = json.dumps(contract.to_dict(), indent=4, sort_keys=True)
    return f'''"""Starter integration for the {contract.name} context contract.

Generated by `python -m context_contract scaffold`. Plug the placeholders into
your service catalog, task object, action builder, and service execution path.
"""

from context_contract import AuditTrace, ContextContract, Gate, focused_view, score_trace


CONTRACT = {contract_literal}


def handle_task(catalog, task, proposed_action):
    """Build a focused view, enforce the gate, record an audit, and score it."""

    contract = ContextContract.from_dict(CONTRACT)
    view = focused_view(catalog, task, contract, k=5)
    gate = Gate(contract)
    decision = gate.check(proposed_action)

    trace = AuditTrace(metadata={{"contract": contract.name, "task": task}})
    trace.append(
        action=proposed_action,
        context_used=[item.get("name", item.get("operation", "")) for item in view],
        obligations_checked=decision.checked,
        decision=decision.to_dict(),
        evidence={{"plug_this_in": "approval, source, state, or policy evidence"}},
    )

    if decision.accepted:
        # Plug the real service call in here.
        service_result = {{"status": "accepted_placeholder"}}
    else:
        # Plug reject handling in here: ask for approval, clarify, or stop.
        service_result = {{"status": "rejected", "reason": decision.reason, "missing": decision.missing}}

    score = score_trace(trace, contract)
    return {{"view": view, "decision": decision.to_dict(), "audit": trace.to_dict(), "score": score.to_dict(), "service_result": service_result}}
'''


def advise_service(service: Mapping[str, Any] | list[Any]) -> dict[str, Any]:
    """Draft a heuristic contract skeleton from a service description."""

    normalized = normalize_service(service)
    operations = normalized["operations"]
    use_case = normalized["use_case"]
    service_text = " ".join([use_case, *(operation_text(operation) for operation in operations)])

    axis_review = {
        "required_context": review_axis(REQUIRED_CONTEXT_RE, service_text, "operations mention required inputs, dependencies, or context"),
        "authority": review_axis(AUTHORITY_RE, service_text, "operations appear irreversible, costly, or externally visible"),
        "provenance": review_axis(PROVENANCE_RE, service_text, "operations mention sources, freshness, claims, or documents"),
        "memory": review_axis(MEMORY_RE, service_text, "the use case appears stateful or multi-step"),
        "privacy": review_axis(PRIVACY_RE, service_text, "operations mention user, customer, account, or personal data"),
        "uncertainty": review_axis(UNCERTAINTY_RE, service_text, "operations mention missing, ambiguous, or conflicting context"),
        "output_audit": {"status": "likely_applies", "reason": "reference implementations should record action, context, decision, and evidence"},
    }

    authority_preconditions = {
        name: ["approval_state=approved"]
        for name, text in operation_texts_by_name(operations).items()
        if AUTHORITY_RE.search(text)
    }
    provenance_preconditions = {
        name: ["source_ids"]
        for name, text in operation_texts_by_name(operations).items()
        if PROVENANCE_RE.search(text)
    }

    contract = ContextContract(
        name=normalized["name"],
        version="draft",
        required_context=ObligationSpec(
            requires=["review task inputs and service preconditions"] if axis_review["required_context"]["status"] == "likely_applies" else []
        ),
        authority=ObligationSpec(
            requires=["human approval before irreversible or externally visible actions"] if authority_preconditions else [],
            preconditions=authority_preconditions,
        ),
        provenance=ObligationSpec(
            requires=["source identity for source-dependent claims"] if provenance_preconditions else [],
            preconditions=provenance_preconditions,
        ),
        memory=ObligationSpec(
            requires=["persist task state across steps"] if axis_review["memory"]["status"] == "likely_applies" else []
        ),
        privacy=ObligationSpec(
            requires=["minimize user, customer, and third-party data"] if axis_review["privacy"]["status"] == "likely_applies" else []
        ),
        uncertainty=ObligationSpec(
            requires=["ask a focused clarification when required context is missing"] if axis_review["uncertainty"]["status"] == "likely_applies" else []
        ),
        output_audit=ObligationSpec(promises=["record action, context, checked obligations, decision, and evidence"]),
        metadata={"source": "context_contract advise heuristic"},
    )

    return {
        "notice": "Heuristic starting point for a human or advisor skill to refine. This command applies transparent keyword rules only.",
        "service": normalized,
        "axis_review": axis_review,
        "contract": contract.to_dict(),
    }


def normalize_service(service: Mapping[str, Any] | list[Any]) -> dict[str, Any]:
    if isinstance(service, list):
        return {"name": "service", "use_case": "", "operations": service}
    operations = service.get("operations", [])
    if not isinstance(operations, list):
        raise ValueError("service.json must contain an operations list")
    return {
        "name": str(service.get("name", service.get("service", "service"))),
        "use_case": str(service.get("use_case", service.get("use_case_note", ""))),
        "operations": operations,
    }


def operation_text(operation: Any) -> str:
    if not isinstance(operation, Mapping):
        return str(operation)
    parts: list[str] = []
    for key in ("name", "operation", "description", "use_case", "notes"):
        if key in operation:
            parts.append(str(operation[key]))
    for key in ("tags", "parameters"):
        value = operation.get(key)
        if isinstance(value, Mapping):
            parts.extend(str(item) for item in value.keys())
            parts.extend(str(item) for item in value.values())
        elif isinstance(value, list):
            parts.extend(str(item) for item in value)
    return " ".join(parts)


def operation_name(operation: Any, index: int) -> str:
    if not isinstance(operation, Mapping):
        return f"operation_{index + 1}"
    return str(operation.get("name", operation.get("operation", f"operation_{index + 1}")))


def operation_texts_by_name(operations: list[Any]) -> dict[str, str]:
    return {
        operation_name(operation, index): operation_text(operation)
        for index, operation in enumerate(operations)
    }


def review_axis(pattern: re.Pattern[str], text: str, reason: str) -> dict[str, str]:
    if pattern.search(text):
        return {"status": "likely_applies", "reason": reason}
    return {"status": "review", "reason": "no simple keyword signal found; human review should confirm"}


if __name__ == "__main__":
    raise SystemExit(main())
